// The string inventory (Stage A, decision 5): every piece of user-facing text written inline in the screens and
// components, counted and listed by area. Reads source, changes none. Stage C moves these strings, screen by screen, into
// utils/copy/<area>.ts with the same words; tests/copy-identical.test.ts holds the baseline written here.
//
//   node --experimental-strip-types scripts/string-inventory.ts            print the counts and compare with the baseline
//   node --experimental-strip-types scripts/string-inventory.ts --write    rewrite the baseline and docs/STRING_INVENTORY.md
//
// Rewrite the baseline only on purpose: a changed baseline is a changed wording, and the point of the test is that
// moving a string never changes it. New screens and features add strings; use --write after a review of the diff.
/// <reference types="node" />
import {readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {missingText, scanSource, type Found} from '../tests/helpers/string-scan.ts';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const SCAN_DIRS = ['app', 'components', 'hooks', 'services'];
export const BASELINE_PATH = 'tests/helpers/string-inventory.baseline.json';
export const DOC_PATH = 'docs/STRING_INVENTORY.md';

export type Entry = Found & {file: string; area: string};

// The area a file belongs to: where the text will live (utils/copy/<area>.ts)
export function areaOf(file: string): string {
  if (file.startsWith('app/admin/') || file === 'services/admin.js' || file === 'services/adminCatalog.js') return 'admin';
  if (file === 'components/startup-trace-panel.tsx') return 'dev';
  if (file === 'app/auth.tsx' || file === 'services/authActions.js') return 'auth';
  if (file === 'app/onboarding.tsx' || file.startsWith('components/onboarding/')) return 'onboarding';
  if (file === 'app/(tabs)/settings.tsx' || file === 'components/switch-row.tsx') return 'settings';
  if (file === 'app/(tabs)/summary.tsx' || file.startsWith('components/summary-')) return 'summary';
  if (file === 'app/(tabs)/profile.tsx' || file === 'components/medal.tsx' || file === 'components/stats-card.tsx') return 'profile';
  if (file === 'app/habit-form.tsx' || file === 'components/habit-fields.tsx' || file === 'components/time-field.tsx') return 'habitForm';
  if (file.startsWith('app/packs/') || file.startsWith('components/packs/')) return 'packs';
  if (file === 'app/reflect.tsx' || file.startsWith('components/reflections/')) return 'reflections';
  if (file === 'app/profile-name.tsx' || file === 'app/profile-setup.tsx') return 'account';
  if (file === 'app/(tabs)/index.tsx' || file.startsWith('components/')) return 'home';
  return 'common';
}

function sourceFiles(dir: string): string[] {
  return readdirSync(join(ROOT, dir)).flatMap((name) => {
    const rel = `${dir}/${name}`;
    if (statSync(join(ROOT, rel)).isDirectory()) return sourceFiles(rel);
    return /\.(tsx|ts|js)$/.test(name) ? [rel] : [];
  });
}

export function scanApp(): Entry[] {
  const entries: Entry[] = [];
  for (const dir of SCAN_DIRS) {
    for (const file of sourceFiles(dir)) {
      for (const found of scanSource(file, readFileSync(join(ROOT, file), 'utf8'))) entries.push({...found, file, area: areaOf(file)});
    }
  }
  return entries.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : a.line - b.line));
}

const label = (e: Entry) => (e.kind === 'attr' ? `prop ${e.attr}` : e.kind);

export function summary(entries: Entry[]) {
  const by = <K extends string>(key: (e: Entry) => K) => {
    const out = new Map<K, number>();
    for (const e of entries) out.set(key(e), (out.get(key(e)) ?? 0) + 1);
    return [...out.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1));
  };
  return {total: entries.length, distinct: new Set(entries.map((e) => e.text)).size, areas: by((e) => e.area), kinds: by((e) => e.kind), files: by((e) => e.file)};
}

function docText(entries: Entry[]): string {
  const s = summary(entries);
  const lines: string[] = [
    '# String inventory',
    '',
    'Every piece of user-facing text written inline in `app/`, `components/`, `hooks/` and `services/` (Stage A, decision 5).',
    'Generated by `scripts/string-inventory.ts`; do not edit by hand. Stage C moves these strings, screen by screen, into',
    '`utils/copy/<area>.ts` with the same words (a value inside a string is written `${…}`). `tests/copy-identical.test.ts` fails if',
    'any text listed here disappears from the app without being in a copy module word for word.',
    '',
    `**${s.total} strings (${s.distinct} distinct).** Alerts: ${s.kinds.find(([k]) => k === 'alert')?.[1] ?? 0}. Text in elements: ${s.kinds.find(([k]) => k === 'text')?.[1] ?? 0}. Props (placeholder, accessibilityLabel, accessibilityHint, label, title): ${s.kinds.find(([k]) => k === 'attr')?.[1] ?? 0}. Sentence-like strings written anywhere else in the code, such as a message a function returns ("literal"): ${s.kinds.find(([k]) => k === 'literal')?.[1] ?? 0}.`,
    '',
    'A "(piece)" is one part of a longer text (words beside a value in JSX, or one side of a +); when the whole text moves, it only has to',
    'be part of a longer literal there.',
    '',
    'What it does not find: text built from a variable or a function call (for example a message returned by a utils/ function: those',
    'already live in utils/, mostly in the existing copy modules), and text in utils/ and constants/. A text that appears in more',
    'than one place counts once per place, and the test checks only that the words still exist somewhere.',
    '',
    '## By area',
    '',
    '| Area | Strings |',
    '|---|---|',
    ...s.areas.map(([area, n]) => `| ${area} | ${n} |`),
    '',
    '## By file',
    '',
    '| File | Strings |',
    '|---|---|',
    ...s.files.map(([file, n]) => `| ${file} | ${n} |`),
    '',
    '## The list',
    '',
  ];
  let current = '';
  for (const e of entries) {
    if (e.file !== current) {
      current = e.file;
      lines.push('', `### ${e.file} (${e.area})`, '');
    }
    lines.push(`- ${e.line} ${label(e)}${e.partial ? ' (piece)' : ''}: ${JSON.stringify(e.text)}`);
  }
  return lines.join('\n') + '\n';
}

const run = process.argv[1]?.endsWith('string-inventory.ts');
if (run) {
  const entries = scanApp();
  const s = summary(entries);
  console.log(`${s.total} strings, ${s.distinct} distinct, in ${s.files.length} files`);
  console.log('by area:', s.areas.map(([k, n]) => `${k} ${n}`).join(', '));
  console.log('by kind:', s.kinds.map(([k, n]) => `${k} ${n}`).join(', '));
  if (process.argv.includes('--write')) {
    const baseline = entries.map(({file, line, kind, attr, text, area, partial}) => ({
      file, line, kind, ...(attr ? {attr} : {}), area, ...(partial ? {partial} : {}), text,
    }));
    writeFileSync(join(ROOT, BASELINE_PATH), JSON.stringify(baseline, null, 1) + '\n');
    writeFileSync(join(ROOT, DOC_PATH), docText(entries));
    console.log(`wrote ${BASELINE_PATH} and ${DOC_PATH}`);
  } else {
    let baseline: {text: string; partial?: boolean}[] = [];
    try {
      baseline = JSON.parse(readFileSync(join(ROOT, BASELINE_PATH), 'utf8'));
    } catch {
      console.log('no baseline yet; run with --write');
    }
    const gone = missingText(baseline, new Set(entries.map((e) => e.text)), []);
    console.log(`baseline: ${baseline.length} entries; text no longer inline: ${gone.length}`);
    for (const t of gone.slice(0, 20)) console.log('  -', JSON.stringify(t));
  }
  console.log(`(scanned from ${relative(process.cwd(), ROOT) || '.'})`);
}
