import {useEffect} from 'react';
import {Alert, AppState} from 'react-native';
import {router, type Href} from 'expo-router';
import {checkAccount} from '@/services/accountStatus';
import {getFirebaseAuth} from '@/services/authInit';
import {signOut} from '@/services/authActions';
import {profileCompletion, profileSetupScreen} from '@/services/profileCompletion';
import {profileNameStore} from '@/services/profileName';
import {getSyncStatus, subscribeSyncStatus} from '@/sync/syncEngine';
import {settleProfile} from '@/services/profileCompletionCore';
import {profileNameFromDoc} from '@/utils/profileName';
import {mark} from '@/utils/startupTrace';

// Signs the user out if an admin has disabled their account. Runs after each sign-in (or launch with a
// saved session) and whenever the app returns to the foreground. Never part of the readiness gate,
// and only a successful server read showing disabled === true (for a non-admin) signs anyone out.
//
// The same server read of users/{uid} (no extra read) also finishes a profile sign-up couldn't confirm
// (services/profileCompletion.ts), and opens "Finish setting up your account" (app/profile-setup.tsx) only when the
// server says there is no profile, the account is not an admin (admins/{uid}, read only in that case) and nothing on
// this phone can complete it. Offline, unknown, or an admin read that failed never opens it.
// While a profile is pending, each finished sync cycle tries again too.
export function useDisabledCheck(uid: string | null) {
  useEffect(() => {
    if (!uid) return;
    let active = true; // false once this uid signs out or another user signs in
    let running = false; // one check at a time per uid
    const current = () => active && getFirebaseAuth().currentUser?.uid === uid;

    const run = () => {
      if (running) return;
      running = true;
      // the users doc read here also refreshes the greeting's name (no extra read)
      checkAccount(uid, (doc: {firstName?: unknown; lastName?: unknown}) => {
        const auth = getFirebaseAuth().currentUser;
        if (!active || auth?.uid !== uid) return;
        void profileNameStore.set(profileNameFromDoc(uid, doc, auth.displayName));
      })
        .then(async ({status, profile, admin}: {
          status: 'disabled' | 'ok' | 'unknown';
          profile: 'exists' | 'missing' | 'unknown';
          admin: boolean | null;
        }) => {
          if (!current()) return; // signed out, or a different user is signed in now
          if (status === 'disabled') {
            await signOut(); // onAuthStateChanged in app/_layout.tsx then shows the sign-in screen
            Alert.alert('Account disabled', 'This account has been disabled. Please contact the HabitQuest team.');
            return;
          }
          // an unknown profile, an admin with no profile, or an admin read that failed: nothing at all. Otherwise
          // 'exists' clears a pending record left from sign-up, and 'missing' writes it now
          const openSetup = await settleProfile(profileCompletion, uid, {profile, admin});
          if (current() && openSetup && !profileSetupScreen.isOpen()) {
            // cast: the typed-routes list is regenerated by the dev server; the route is app/profile-setup.tsx
            router.push('/profile-setup' as Href);
          }
        })
        .catch((err: unknown) => console.log('Account check failed', err))
        .finally(() => {
          running = false;
          mark('disabled:done');
        });
    };

    run();
    const subscription = AppState.addEventListener('change', (next) => {
      if (next === 'active') run();
    });
    // after each sync cycle, only while something is pending (one local read)
    let syncing = getSyncStatus().state === 'syncing';
    const unsubscribeSync = subscribeSyncStatus((s: {state: string}) => {
      const ended = syncing && s.state !== 'syncing';
      syncing = s.state === 'syncing';
      if (!ended || running) return;
      void profileCompletion.hasPending(uid).then((pending) => {
        if (pending && current()) run();
      });
    });
    return () => {
      active = false;
      subscription.remove();
      unsubscribeSync();
    };
  }, [uid]);
}
